/**
 * Aplica as traduções ao DOM para o idioma especificado.
 * Todos os elementos com atributo data-i18n terão seu textContent atualizado.
 * Elementos com data-i18n-title terão seu atributo title atualizado.
 */
function applyTranslations(lang) {
    const dict = translations[lang];
    if (!dict) return;

    // Traduz textContent de todos os elementos com data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.textContent = dict[key];
        }
    });

    // Traduz atributo title de elementos com data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (dict[key] !== undefined) {
            el.setAttribute('title', dict[key]);
        }
    });

    // Atualiza o atributo lang do <html>
    const langMap = { pt: 'pt-BR', es: 'es', en: 'en', fr: 'fr', de: 'de', it: 'it' };
    document.documentElement.lang = langMap[lang] || lang;
}
